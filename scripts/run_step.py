"""
Run one step of a model's ladder: train it (timed), benchmark it, update the site.

    python scripts/run_step.py experiments/neat/n01_lap_time.toml
    python scripts/run_step.py experiments/ppo/p00_baseline.toml --benchmark-only

Writes to outputs/<model>/<step id>/:
    checkpoints/, logs/       training artefacts (git-ignored)
    model.pkl | model.zip     the selected model (best on validation / eval)
    neat.cfg                  NEAT only: the config this step used
    result.json               settings, training time, size, lap times per track, curves
    drives.json               the benchmark drives, recorded for the race page
    lap.gif                   the drive on the first benchmark track
then runs scripts/build_site.py.
"""

from __future__ import annotations

import argparse
import configparser
import csv
import datetime as dt
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Import everything up front: a step can train for hours, and a lazy import
# would pick up code edited in the meantime.
from carracing.benchmark import GIF_SEED, SEEDS, drive, load_policy, save_gif  # noqa: E402
from carracing.steps import (  # noqa: E402
    Step, fmt_duration, hardware, load_step, neat_train_seconds, ppo_train_seconds, summarise, train_flags,
)
from carracing_neat.eval import load_genome  # noqa: E402
from carracing_neat.graph import genome_graph, input_spec, output_spec  # noqa: E402

BASE_NEAT_CONFIG = "neat_config/neat.cfg"


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def write_neat_config(step: Step) -> str:
    """neat_config/neat.cfg + this step's [neat_config] overrides + num_inputs for its lidar."""
    parser = configparser.ConfigParser()
    parser.read(BASE_NEAT_CONFIG)
    overrides = {"DefaultGenome.num_inputs": step.state_inputs, **step.neat_config}
    for dotted, value in overrides.items():
        section, key = dotted.split(".", 1)
        if not parser.has_option(section, key):
            raise SystemExit(f"{step.path}: neat_config key {dotted!r} is not in {BASE_NEAT_CONFIG}")
        parser.set(section, key, str(value).lower() if isinstance(value, bool) else str(value))
    path = os.path.join(step.out_dir, "neat.cfg")
    with open(path, "w") as fh:
        fh.write(f"# Generated by scripts/run_step.py for {step.id}: {BASE_NEAT_CONFIG} + overrides {overrides}\n")
        parser.write(fh)
    return path


def train(step: Step) -> float:
    ckpt, logs = os.path.join(step.out_dir, "checkpoints"), os.path.join(step.out_dir, "logs")
    os.makedirs(logs, exist_ok=True)
    flags = train_flags(step.train) + ["--checkpoint-dir", ckpt, "--log-dir", logs] + step.env_flags()
    if step.model == "neat":
        cmd = [sys.executable, "-m", "carracing_neat.train", "--config", os.path.join(step.out_dir, "neat.cfg")]
    else:
        cmd = [sys.executable, "-m", "carracing_ppo.train"]
    cmd += flags
    print("$", " ".join(cmd), flush=True)
    with open(os.path.join(logs, "command.txt"), "w") as fh:
        fh.write(" ".join(cmd) + "\n")
    start = time.time()
    with open(os.path.join(logs, "train.out"), "a") as out:
        proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
        for line in proc.stdout:
            sys.stdout.write(line)
            out.write(line)
        if proc.wait() != 0:
            raise SystemExit(f"Training failed (exit {proc.returncode}); see {logs}/train.out")
    return time.time() - start


def select_neat(step: Step) -> dict:
    """The validated best genome, its generation and the time it took to get there."""
    logs = os.path.join(step.out_dir, "logs")
    if step.imported.get("model"):
        src = os.path.join(step.out_dir, step.imported["model"])
        gen = int(re.search(r"gen-(\d+)", src).group(1))
    else:
        rows = np.genfromtxt(os.path.join(logs, "validation.csv"), delimiter=",", names=True)
        rows = np.atleast_1d(rows)
        gen = int(rows["generation"][int(np.argmax(rows["validation_score"]))])
        src = os.path.join(step.out_dir, "checkpoints", f"best-genome-gen-{gen}.pkl")
    seconds = step.imported.get("train_seconds") or neat_train_seconds(os.path.join(logs, "fitness.csv"), gen)
    return {"src": src, "selected": {"generation": gen}, "train_seconds": float(seconds)}


def select_ppo(step: Step) -> dict:
    """best_model.zip (best mean eval reward), its timestep and the time it took to get there."""
    logs = os.path.join(step.out_dir, "logs")
    src = os.path.join(step.out_dir, step.imported.get("model", "checkpoints/best_model.zip"))
    ev = np.load(os.path.join(logs, "evaluations.npz"))
    ts = int(ev["timesteps"][int(np.argmax(ev["results"].mean(axis=1)))])
    seconds = step.imported.get("train_seconds") or ppo_train_seconds(logs, ts)
    return {"src": src, "selected": {"timestep": ts}, "train_seconds": float(seconds)}


def neat_curves(step: Step) -> dict:
    """Training curve against wall-clock, and every generation's champion network."""
    logs = os.path.join(step.out_dir, "logs")
    with open(os.path.join(logs, "fitness.csv")) as fh:
        fitness = list(csv.DictReader(fh))
    validation = {}
    if os.path.exists(os.path.join(logs, "validation.csv")):
        with open(os.path.join(logs, "validation.csv")) as fh:
            validation = {int(r["generation"]): float(r["validation_score"]) for r in csv.DictReader(fh)}
    curve = []
    for row in fitness:
        gen = int(row["generation"])
        curve.append({"gen": gen, "t": neat_train_seconds(os.path.join(logs, "fitness.csv"), gen),
                      "best": round(float(row["best_fitness"]), 1), "mean": round(float(row["mean_fitness"]), 1),
                      "val": round(validation[gen], 1) if gen in validation else None})
    cfg_path = os.path.join(step.out_dir, "neat.cfg")
    gens = []
    for path in glob.glob(os.path.join(step.out_dir, "checkpoints", "best-genome-gen-*.pkl")):
        gen = int(re.search(r"gen-(\d+)\.pkl$", path).group(1))
        genome, config = load_genome(path, cfg_path)
        gens.append({"gen": gen, "id": genome.key, "validation": round(validation[gen], 1) if gen in validation else None,
                     **genome_graph(genome, config)})
    gens.sort(key=lambda g: g["gen"])
    _, config = load_genome(step.model_path, cfg_path)
    return {"curve": curve, "generations": gens, "inputs": input_spec(config, step.lidar_fov, step.drop_heading),
            "outputs": output_spec(config)}


def ppo_curves(step: Step) -> dict:
    logs = os.path.join(step.out_dir, "logs")
    ev = np.load(os.path.join(logs, "evaluations.npz"))
    curve = [{"steps": int(ts), "t": ppo_train_seconds(logs, int(ts)), "eval": round(float(r.mean()), 1)}
             for ts, r in zip(ev["timesteps"], ev["results"])]
    return {"curve": curve}


def trained_on(step: Step) -> str:
    """Date of the last training log write (re-benchmarking later keeps the training date)."""
    logs = glob.glob(os.path.join(step.out_dir, "logs", "*"))
    stamp = max(os.path.getmtime(p) for p in logs) if logs else time.time()
    return dt.date.fromtimestamp(stamp).isoformat()


def read_lap_checks(step: Step) -> list:
    """Rows of logs/validation_laps.csv: the lap check on the 5 validation tracks during training."""
    path = os.path.join(step.out_dir, "logs", "validation_laps.csv")
    if not os.path.exists(path):
        return []
    with open(path) as fh:
        rows = list(csv.DictReader(fh))
    key = "generation" if step.model == "neat" else "timestep"
    return [{"at": int(r[key]), "t": float(r["time_s"]), "finished": int(r["finished"]),
             "lap": float(r["mean_lap_s"]) if r["mean_lap_s"] else None} for r in rows]


def checkpoint_for(step: Step, at: int) -> str:
    if step.model == "neat":
        return os.path.join(step.out_dir, "checkpoints", f"best-genome-gen-{at}.pkl")
    return os.path.join(step.out_dir, "checkpoints", f"val_{at}.zip")


def select_categories(step: Step) -> dict:
    """Championship checkpoints, chosen on the validation tracks only.

    finish: the first checkpoint that laps all 5 validation tracks (and how long that took);
    fast:   the fastest validation mean lap (most tracks finished first; the earlier one on a tie).
    """
    rows = read_lap_checks(step)
    if not rows:
        raise SystemExit(f"{step.id}: no logs/validation_laps.csv, so no championship checkpoints")
    kind = "generation" if step.model == "neat" else "timestep"
    first = next((r for r in rows if r["finished"] == 5), None)
    fast = max(rows, key=lambda r: (r["finished"], -(r["lap"] or 1e9), -r["t"]))
    out = {}
    for name, row in (("finish", first), ("fast", fast)):
        out[name] = None if row is None else {
            "src": checkpoint_for(step, row["at"]), "selected": {kind: row["at"]}, "train_seconds": row["t"],
            "validation": {"finished": row["finished"], "mean_lap_s": row["lap"]}}
    return out


def benchmark(step: Step, model_path: str = None, gif: str = "lap.gif") -> tuple:
    policy = load_policy(step, model_path)
    tracks, drives = [], {}
    for seed in SEEDS:
        out = drive(policy, seed, step.env_kwargs(), gif=seed == GIF_SEED, activations=step.model == "neat")
        tracks.append(out["result"])
        drives[str(seed)] = out["recording"]
        res = out["result"]
        print(f"  track {seed:>2}: " + (f"lap {res['lap_s']:.2f} s" if res["finished"] else
                                        f"DNF ({res['reached_pct']:.0f}% of the lap)") + f", score {res['score']}",
              flush=True)
        if out["frames"]:
            save_gif(out["frames"][60:660], os.path.join(step.out_dir, gif))
    return tracks, drives, policy.size()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("step", help="experiments/<model>/<id>.toml")
    parser.add_argument("--benchmark-only", action="store_true", help="Skip training; re-select and re-score.")
    parser.add_argument("--no-site", action="store_true", help="Don't run scripts/build_site.py afterwards.")
    args = parser.parse_args()

    step = load_step(args.step)
    os.makedirs(step.out_dir, exist_ok=True)
    if step.model == "neat":
        write_neat_config(step)

    process_seconds = None
    if not (args.benchmark_only or step.imported):
        process_seconds = round(train(step), 1)

    categories = {}
    if step.championship:
        for name, pick in select_categories(step).items():
            if pick is None:
                print(f"{step.id}: never finished all 5 validation tracks, so no '{name}' entry")
                categories[name] = None
                continue
            shutil.copyfile(pick["src"], step.model_file(name))
            print(f"{step.id} [{name}]: {pick['selected']} after {fmt_duration(pick['train_seconds'])} of training")
            c_tracks, c_drives, c_size = benchmark(step, step.model_file(name), "lap.gif" if name == "fast" else f"lap_{name}.gif")
            with open(os.path.join(step.out_dir, f"drives_{name}.json"), "w") as fh:
                json.dump(c_drives, fh, separators=(",", ":"))
            categories[name] = {k: v for k, v in pick.items() if k != "src"}
            categories[name].update(size=c_size, summary=summarise(c_tracks), tracks=c_tracks)
        if categories.get("fast") is None:
            raise SystemExit(f"{step.id}: no lap check rows to pick from")
        picked = select_categories(step)["fast"]
        shutil.copyfile(picked["src"], step.model_path)
        tracks, drives, size = categories["fast"]["tracks"], json.load(open(os.path.join(step.out_dir, "drives_fast.json"))), categories["fast"]["size"]
    elif step.train.get("lap-check-frequency"):
        # Pick by lap check on the validation tracks (as championship cars do), not by PPO's eval reward.
        picked = select_categories(step)["fast"]
        shutil.copyfile(picked["src"], step.model_path)
        print(f"{step.id}: selected {picked['selected']} by lap check after {fmt_duration(picked['train_seconds'])}")
        tracks, drives, size = benchmark(step)
    else:
        picked = select_neat(step) if step.model == "neat" else select_ppo(step)
        shutil.copyfile(picked["src"], step.model_path)
        print(f"{step.id}: selected {picked['selected']} after {fmt_duration(picked['train_seconds'])} of training")
        tracks, drives, size = benchmark(step)
    curves = neat_curves(step) if step.model == "neat" else ppo_curves(step)
    result_path = os.path.join(step.out_dir, "result.json")
    previous = json.load(open(result_path)) if os.path.exists(result_path) else {}
    result = {
        "id": step.id, "model": step.model, "title": step.title, "why": step.why, "parent": step.parent,
        "lidar_rays": step.lidar_rays, "lidar_fov": step.lidar_fov, "drop_heading": step.drop_heading, "train": step.train, "neat_config": step.neat_config,
        "imported": bool(step.imported), "note": step.imported.get("note", ""),
        "hardware": step.imported.get("hardware") or previous.get("hardware") or hardware(),
        "commit": step.imported.get("commit") or (git_commit() if process_seconds else previous.get("commit", git_commit())),
        "trained_on": step.imported.get("trained_on") or previous.get("trained_on") or trained_on(step),
        "train_seconds": picked["train_seconds"],
        "process_seconds": process_seconds or previous.get("process_seconds"),
        "selected": picked["selected"], "size": size, "summary": summarise(tracks), "tracks": tracks, **curves,
        "championship": step.championship, "categories": categories or None,
        "lap_checks": read_lap_checks(step),
    }
    with open(result_path, "w") as fh:
        json.dump(result, fh, indent=1, ensure_ascii=False)
    with open(os.path.join(step.out_dir, "drives.json"), "w") as fh:
        json.dump(drives, fh, separators=(",", ":"))
    s = result["summary"]
    print(f"{step.id}: finished {s['finished']}/5, mean lap {s['lap_s']} s, trained {fmt_duration(result['train_seconds'])}, "
          f"size {size['label']}. Wrote {result_path}")

    if not args.no_site:
        subprocess.run([sys.executable, os.path.join(os.path.dirname(__file__), "build_site.py")], check=True)


if __name__ == "__main__":
    main()
